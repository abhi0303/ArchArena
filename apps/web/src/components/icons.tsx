export function DynamicIcon({ name, className, strokeWidth }: { name: string; className?: string; strokeWidth?: number }) {
  const Icon = ICONS[name] ?? Box;
  return <Icon className={className} strokeWidth={strokeWidth} aria-hidden />;
}

